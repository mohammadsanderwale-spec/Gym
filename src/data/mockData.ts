// Helper to generate ISO dates relative to today
const now = new Date();
const daysAgo = (d: number) => {
  const date = new Date(now.getTime() - d * 24 * 60 * 60 * 1000);
  return date.toISOString().split('T')[0];
};
const daysFuture = (d: number) => {
  const date = new Date(now.getTime() + d * 24 * 60 * 60 * 1000);
  return date.toISOString().split('T')[0];
};

